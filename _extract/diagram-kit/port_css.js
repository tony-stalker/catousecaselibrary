/* Runs inside kit-host.html (light theme). Renders a corpus of every figure in every state plus the
   spotlight variants, then walks the source stylesheet and returns the CSS rules that style that
   corpus, rewritten with x- prefixed classes, ids, custom properties and keyframes.
   Loaded by _extract/build-diagrams.py; output lands in the style.css dg-kit block. */
(() => {
  const K = window.__KIT;
  const corpus = document.createElement('div'); corpus.id = 'x-corpus';
  corpus.style.cssText = 'position:absolute;left:-99999px;top:0;width:1600px';
  document.body.appendChild(corpus);
  /* every figure in every state a spec can ask for: each view, detailed, failed over */
  Object.keys(K.FIGS).forEach(id => { [null, 'detailed', 'fig-fail'].forEach(state => {
    const h = document.createElement('div'); corpus.appendChild(h);
    try { const sv = K.mountSpec(id, h, K.FIG_VB[id] || '0 0 760 560', id); if (state) sv.classList.add(state);
      const views = [...new Set([...sv.querySelectorAll('[data-vw]')].flatMap(g => g.dataset.vw.split(' ')))];
      views.forEach(v => { const h2 = document.createElement('div'); corpus.appendChild(h2);
        const s2 = K.mountSpec(id, h2, K.FIG_VB[id] || '0 0 760 560', id); if (state) s2.classList.add(state);
        s2.querySelectorAll('[data-vw]').forEach(g => { g.style.display = g.dataset.vw.split(' ').includes(v) ? '' : 'none'; }); });
    } catch (e) {} }); });
  [null].concat(K.USE_CASES).forEach(uc => { const h = document.createElement('div'); corpus.appendChild(h); K.spotlight(uc, h); });
  /* states the bundled use cases never produce: two steps on one anchor (a pill marker) and the attack path */
  { const h = document.createElement('div'); corpus.appendChild(h);
    K.spotlight({ hl: ['pop'], flows: [{ p: 'atk' }, { p: 'br1' }], steps: [{ marks: ['pop'] }, { marks: ['pop'] }] }, h); }

  const UI = /(^|[\s>+~(,])(\.(stage|scene|detail|d-[\w-]+|bar|top|uc-rail|rail|panel|pn-[\w-]+|lic[\w-]*|popmap|pm-[\w-]+|help|menu|chips|chip-nav|btn|lightbox|laser|lens-tip|app|wrap)|#(scene|detail|panel|menu|help|popmap|app|stage))(?![\w-])/;
  const STATE = /:(hover|focus|focus-visible|focus-within|active|checked)/;
  const sheet = [...document.styleSheets].find(s => { try { return s.cssRules.length > 100; } catch (e) { return false; } });
  const base = [], light = [], keyframes = new Map(), tokens = { dark: '', light: '' };
  const rxClass = /\.(-?[_a-zA-Z][\w-]*)/g;
  const prefixSel = sel => sel.replace(rxClass, '.x-$1').replace(/#([_a-zA-Z][\w-]*)/g, '#x-$1');
  /* url() declarations are dropped: paint servers are baked into element attributes at export time */
  const dropUrl = txt => txt.split(';').filter(d => !/url\(/.test(d)).join(';');
  const fixDecl = txt => dropUrl(txt).replace(/var\(--([\w-]+)/g, 'var(--x-$1')
    .replace(/\banimation(-name)?\s*:\s*([^;]+)/g, (m, n, v) => m.replace(/\b(dash|spin|halo|pulse|enter)\b/g, 'x-$1'));
  for (const r of sheet.cssRules) {
    if (r.type === CSSRule.KEYFRAMES_RULE) { keyframes.set(r.name, r.cssText); continue; }
    if (r.type !== CSSRule.STYLE_RULE) continue;
    const isLight = /:root\[data-theme="light"\]/.test(r.selectorText);
    if (r.selectorText === ':root') { tokens.dark = r.style.cssText; continue; }
    if (r.selectorText === ':root[data-theme="light"]') { tokens.light = r.style.cssText; continue; }
    const kept = [];
    for (let s of r.selectorText.split(/,(?![^(]*\))/)) {
      s = s.trim().replace(/^:root\[data-theme="light"\]\s*/, '');
      if (!s || STATE.test(s) || UI.test(' ' + s) || /^(html|body|\*|:root)/.test(s)) continue;
      let hit = false; try { hit = !!corpus.querySelector(s); } catch (e) { hit = false; }
      if (hit) kept.push(s);
    }
    if (!kept.length) continue;
    const decl = r.style.cssText; if (!decl) continue;
    (isLight ? light : base).push({ sel: kept.map(prefixSel).join(','), raw: kept, decl: fixDecl(decl) });
  }
  /* custom properties: source :root = dark palette, :root[data-theme=light] = light palette */
  const tok = t => t.split(';').map(x => x.trim()).filter(x => /^--/.test(x) && !/^--(display|body|mono)\b/.test(x))
    .map(x => x.replace(/^--/, '--x-')).join('; ');
  const usedKF = new Set(); [...base, ...light].forEach(r => (r.decl.match(/x-(dash|spin|halo|pulse|enter)\b/g) || []).forEach(k => usedKF.add(k.slice(2))));
  let css = '/* ---- generated by _extract/build-diagrams.py from the platform-overview kit — do not edit by hand ---- */\n';
  css += ':root{' + tok(tokens.light) + '; --x-display: var(--font); --x-body: var(--font); --x-mono: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace}\n';
  css += '@media screen{:root[data-theme="dark"]{' + tok(tokens.dark) + '}}\n';
  base.forEach(r => { css += r.sel + '{' + r.decl + '}\n'; });
  css += '/* light-theme refinements from the source become the library default; dark restores the source base */\n';
  light.forEach(r => {
    css += r.sel + '{' + r.decl + '}\n';
    const props = r.decl.split(';').map(d => d.split(':')[0].trim()).filter(Boolean);
    const orig = base.find(b => b.sel === r.sel);
    if (orig) { const keep = orig.decl.split(';').map(d => d.trim()).filter(d => props.includes(d.split(':')[0].trim()));
      if (keep.length) css += '@media screen{:root[data-theme="dark"] ' + r.sel.split(',').join(',:root[data-theme="dark"] ') + '{' + keep.join(';') + '}}\n'; }
  });
  usedKF.forEach(k => { if (keyframes.has(k)) css += keyframes.get(k).replace('@keyframes ' + k, '@keyframes x-' + k) + '\n'; });
  corpus.remove();
  return { css, nBase: base.length, nLight: light.length, kf: [...usedKF], lightRules: light.map(r => r.sel) };
})()
